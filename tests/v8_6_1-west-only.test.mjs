const content = p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
test('West es inmutable y AODP solo tiene un origen numerico',()=>{
 assert.equal(REGION,'west');assert.equal(NUMERIC_SOURCE.server,'west');assert.equal(requireWest('west'),'west');
 for(const region of ['europe','east','EU',''])assert.throws(()=>requireWest(region),/América/);
 assert.equal(NUMERIC_SOURCE.base,'https://west.albion-online-data.com');
 assert(!WEST_MARKET_SOURCES.some(s=>s.key==='albion-journal'));
 assert(WEST_MARKET_SOURCES.every(s=>s.numericApi===false));
});
test('la API de mercado no consulta Europa, ni directa ni por proxy',async()=>{
 await assert.rejects(prices(['T5_SHOES_PLATE_SET1'],'europe'),/América/);
 await assert.rejects(prices(['T5_SHOES_PLATE_SET1'],'east'),/América/);
 const req=new Request('https://test.invalid/.netlify/functions/market?region=europe&kind=prices&items=T5_SHOES_PLATE_SET1');
 const res=await marketHandler(req);assert.equal(res.status,400);
 assert.match(content('netlify/functions/snapshot.mjs'),/region!=='west'/);
 assert.match(content('netlify/functions/hourly-prices.mjs'),/const region='west'/);
});
test('AODP-only: ninguna página externa se comprueba, sin prometer ventas',async()=>{
 let calls=0;
 const result=await verifyMarketReferences(async()=>{calls++;throw Error('No consultar')});
 assert.equal(calls,0);assert.equal(result.region,'west');assert.deepEqual(result.checks,[]);
 assert.equal(result.usedForPrices,true);assert.equal(result.usedForMarketVolume,true);
 assert.deepEqual(marketReferenceSnapshot(result),[]);
 assert.equal((await verifyMarketReferences(async()=>{throw Error('Unexpected fetch')},{region:'europe'})).checks.length,0);
 assert.equal((await (await import('../netlify/functions/market-references.mjs')).default(new Request('https://test.invalid/.netlify/functions/market-references?region=europe'))).status,400);
});
test('la importacion West exige declaracion, fecha y no admite etiquetas Europe/Asia',()=>{
 const row={id:'T5_SHOES_PLATE_SET2',city:'Black Market',daily:3696};
 const base={source:'hub',region:'west',observedAt:new Date().toISOString(),rows:[row]};
 assert.equal(validMarketSnapshot(base),false);
 assert.equal(validMarketSnapshot({...base,serverProof:'user-confirmed-west'}),true);
 assert.equal(externalDaily({...base,serverProof:'user-confirmed-west'},row.id,row.city).daily,3696);
 assert.equal(validMarketSnapshot({...base,source:'journal',serverProof:'user-confirmed-west'}),false);
 assert.equal(validMarketSnapshot({...base,region:'europe',serverProof:'user-confirmed-west'}),false);
 assert.equal(conflictingServerLabel('SERVER: EUROPE'),true);
 assert.equal(conflictingServerLabel('West / Americas'),false);
 assert.deepEqual(parseMarketRanking('T5_SHOES_PLATE_SET2 Europe Black Market 3,696',{source:'hub'}),[]);
 assert.deepEqual(parseMarketRanking('T5_SHOES_PLATE_SET2 Black Market 3,696',{source:'journal'}),[]);
});
