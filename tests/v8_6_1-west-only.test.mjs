import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {REGION,requireWest,WEST_MARKET_SOURCES,NUMERIC_SOURCE} from '../core/server-policy.js';
import {parseMarketRanking,validMarketSnapshot,externalDaily,conflictingServerLabel} from '../core/external-demand.js';
